import 'dart:async';
import 'dart:io' show Platform;

import 'package:firebase_core/firebase_core.dart';
import 'package:flutter/foundation.dart';
import 'package:flutter/material.dart';
import 'package:flutter/services.dart';
import 'package:google_mobile_ads/google_mobile_ads.dart';

import 'app.dart';
import 'core/config/app_config.dart';
import 'firebase_options.dart';

Future<void> main() async {
  WidgetsFlutterBinding.ensureInitialized();
  await SystemChrome.setPreferredOrientations([DeviceOrientation.portraitUp]);
  SystemChrome.setEnabledSystemUIMode(SystemUiMode.edgeToEdge);

  final firebaseReady = await _initFirebase();

  if (!kIsWeb && (Platform.isAndroid || Platform.isIOS)) {
    try {
      await _gatherAdConsent();
      await MobileAds.instance.initialize();
    } catch (e) {
      debugPrint('AdMob initialization error: $e');
    }
  }

  runApp(GearSpinApp(firebaseReady: firebaseReady));
}

/// Google User Messaging Platform: shows the consent form (configured in
/// AdMob > Privacy & messaging) when the user's region requires it. Never
/// blocks the game for long and never throws.
Future<void> _gatherAdConsent() async {
  final done = Completer<void>();
  ConsentInformation.instance.requestConsentInfoUpdate(
    ConsentRequestParameters(),
    () async {
      try {
        await ConsentForm.loadAndShowConsentFormIfRequired((FormError? error) {
          if (error != null) debugPrint('Consent form error: ${error.message}');
          if (!done.isCompleted) done.complete();
        });
      } catch (e) {
        debugPrint('Consent form failed: $e');
        if (!done.isCompleted) done.complete();
      }
    },
    (FormError error) {
      debugPrint('Consent info update failed: ${error.message}');
      if (!done.isCompleted) done.complete();
    },
  );
  await done.future.timeout(const Duration(seconds: 10), onTimeout: () {});
}

/// Never blocks the game: any failure just means "run offline".
///
/// Uses the options generated by `flutterfire configure`
/// ([DefaultFirebaseOptions]), so it works on Android and iOS without
/// depending on the native config files being present.
Future<bool> _initFirebase() async {
  if (!useFirebase) return false;
  try {
    await Firebase.initializeApp(options: DefaultFirebaseOptions.currentPlatform);
    return true;
  } catch (e) {
    debugPrint('Firebase init failed, running offline: $e');
    return false;
  }
}
